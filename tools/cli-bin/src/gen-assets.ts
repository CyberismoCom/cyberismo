// Generates embedded-assets.gen.ts: one `type: 'file'` import per static
// asset, so `bun build --compile` embeds them and we know each logical path.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const here = import.meta.dirname;
const roots: [prefix: string, dir: string][] = [
  ['static', resolve(here, '../../assets/dist/static')],
  ['public', resolve(here, '../../backend/dist/public')],
];

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}

const hash = createHash('sha256');
const imports: string[] = [];
const entries: string[] = [];
for (const [prefix, dir] of roots) {
  for (const file of walk(dir).sort()) {
    const logical = `${prefix}/${relative(dir, file)}`;
    hash.update(logical).update(readFileSync(file));
    const id = `f${imports.length}`;
    imports.push(
      `import ${id} from ${JSON.stringify(relative(here, file))} with { type: 'file' };`,
    );
    entries.push(`  [${JSON.stringify(logical)}, ${id}],`);
  }
}

writeFileSync(
  join(here, 'embedded-assets.gen.ts'),
  `// Generated by gen-assets.ts. Do not edit.\n// @ts-nocheck\n${imports.join('\n')}\n\n` +
    `export const assetsHash = '${hash.digest('hex').slice(0, 16)}';\n` +
    `export const embeddedAssets: [string, string][] = [\n${entries.join('\n')}\n];\n`,
);
console.log(`embedded ${entries.length} files`);
